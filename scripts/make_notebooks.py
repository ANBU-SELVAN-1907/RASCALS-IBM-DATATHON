    md("### Interpretation\nThe reported throughput is a timed in-process benchmark on the assigned VM, using synthetic inputs. It is not a load test of the full HTTP ingestion endpoint or a platform-wide performance claim. CPU quota, offered volume, dropped/rejected counts and measurement boundaries are reported explicitly."),
