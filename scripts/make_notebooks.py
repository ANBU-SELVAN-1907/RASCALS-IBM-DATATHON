for name, cells in [('01_train_and_evaluate.ipynb', training), ('02_test_and_benchmark.ipynb', testing)]:
    for cell in cells:
        cell['id']=hashlib.sha256((cell['cell_type']+cell['source']).encode()).hexdigest()[:12]
    notebook = {'cells': cells, 'metadata': {'kernelspec': {'display_name': 'Python 3 (LinuxONE)', 'language': 'python', 'name': 'python3'}, 'language_info': {'name': 'python'}}, 'nbformat': 4, 'nbformat_minor': 5}
    (DEST/name).write_text(json.dumps(notebook, indent=1), encoding='utf-8')
    print(DEST/name)
